--   - crawler_rca_engine.py:675 calls RPC refresh_crawler_stats_cache
--     (non-v2) — function name/signature unchanged, still valid.
--
-- BEHAVIOR NOTE (intentional, documented tradeoff):
--   industries_breakdown now comes from mv_crawler_industries_30d, which
