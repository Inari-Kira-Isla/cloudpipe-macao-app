--      refresh_crawler_stats_cache_v2() only REFRESHes the 4 mv_crawler_*_30d
--      materialized views — it never writes to crawler_stats_cache.
--   2. The OLD refresh_crawler_stats_cache() (the function that actually writes
--      the crawler_stats_cache table every downstream consumer reads) is no
--      longer called by ANY scheduled job. It only ran when something hit the
--      RPC directly (e.g. aeo_monitor_hourly.py trigger_refresh()).
--   3. That old function does a full ad-hoc scan of crawler_visits (30d window,
--      several GROUP BYs materialized via a CTE) which takes ~7-8s when run
--      directly. When invoked through PostgREST-facing roles (authenticated/
--      anon/authenticator all have statement_timeout=8s / 3s configured on the
--      role, see pg_roles.rolconfig), it gets killed by Postgres error 57014
--      (query_canceled) before finishing — confirmed via direct curl RPC call
--      (8.27s wall time, 57014) and independently by introspecting pg_roles.
--   4. Net effect: crawler_stats_cache.daily_30d / daily_by_owner_30d froze
--      around 2026-06-04 and never advanced, silently, because the whole
--      function body is wrapped in `EXCEPTION WHEN OTHERS THEN RAISE WARNING`
--      (see historical add_crawler_stats_cache_auto_refresh.sql lines ~108-111)
--      which swallows the 57014 and skips the UPSERT entirely.
--
-- FIX (this migration):
--   A. Rewrite refresh_crawler_stats_cache() to read from the 4 already-fresh
--      mv_crawler_*_30d materialized views (refreshed every 30 min by the
--      existing v2 cron job, confirmed fresh: computed_at = today, MAX(day)
--      on mv_crawler_daily_30d = today) instead of re-scanning crawler_visits
--      via a slow CTE. Only two lightweight independent queries remain against
--      crawler_visits directly (total_visits_90d, sites_breakdown) because
--      neither is covered by any MV — both benchmarked at ~2s each using the
--      existing idx_crawler_visits_ts / idx_crawler_visits_site_ts indexes,
--      not the slow multi-aggregate CTE that caused the timeout.
--   B. Chain refresh_crawler_stats_cache() onto the SAME pg_cron job right
--      after refresh_crawler_stats_cache_v2(), so crawler_stats_cache gets
--      refreshed automatically every 30 min again, using MV data that was
--      just refreshed in the preceding statement of the same job run.
--   C. Add crawler_stats_cache.last_refresh_error so a stuck/failing refresh
--      is visible from the table itself (not just pg_cron / dashboard logs).
--
-- CONSUMERS THAT NEED ZERO CHANGES because they only read the
-- crawler_stats_cache TABLE (not the MVs directly):
--   - aeo_monitor_hourly.py       (reads total_visits_1d/7d)
--   - cohort_20day_tracker.py     (reads via crawler_stats_cache SSOT)
--   - analysis_to_bulletin_bridge.py (reads total_visits_1d/7d, daily_30d)
--   - daily_data_cross_validator.py  (reads daily_by_owner_30d local mirror)
--   - crawler_stats_precompute.py (reads bots_breakdown/sites_breakdown/
--     industries_breakdown/daily_30d/daily_by_owner_30d — all field names
--     and JSON shapes are preserved unchanged below)
--   - /api/v1/crawler-stats/route.ts (reads the precomputed GitHub Pages
--     cache generated by crawler_stats_precompute.py above; not this table
