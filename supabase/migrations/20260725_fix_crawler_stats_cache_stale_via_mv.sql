-- ---------------------------------------------------------------------------
-- C. Visibility: last_refresh_error so a stuck refresh is visible from the
--    table itself, not just pg_cron/dashboard logs.
-- ---------------------------------------------------------------------------
ALTER TABLE public.crawler_stats_cache
  ADD COLUMN IF NOT EXISTS last_refresh_error TEXT;

-- ---------------------------------------------------------------------------
-- A. New function body: read from the 4 fresh MVs instead of re-scanning
--    crawler_visits. Field names / JSON shapes unchanged for all consumers.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.refresh_crawler_stats_cache()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $function$
DECLARE
  v_since_90d      TIMESTAMPTZ := NOW() - INTERVAL '90 days';
  v_since_30d      TIMESTAMPTZ := NOW() - INTERVAL '30 days';
  v_total_1d       INTEGER;
  v_total_7d       INTEGER;
  v_total_30d      INTEGER;
  v_total_90d      INTEGER;
  v_unique_bots    INTEGER;
  v_bots           JSONB;
  v_sites          JSONB;
  v_industries     JSONB;
  v_daily          JSONB;
  v_daily_by_owner JSONB;
BEGIN
  -- Give this a generous ceiling too (kept from the previous version) —
  -- should be moot now since every branch below is fast, but protects
  -- against a future regression silently reintroducing a slow scan.
  PERFORM set_config('statement_timeout', '30000', true);

  -- ── 1) total_visits_1d/7d/30d + unique_bots: single-row MV, already fresh ──
  SELECT total_visits_1d, total_visits_7d, total_visits_30d, unique_bots
    INTO v_total_1d, v_total_7d, v_total_30d, v_unique_bots
  FROM public.mv_crawler_total_visits_30d;

  -- ── 2) total_visits_90d: not covered by any MV — lightweight independent
  --      count using idx_crawler_visits_ts (~2s benchmarked, not the slow
  --      multi-aggregate CTE that caused the original timeout) ──
  SELECT COUNT(*) INTO v_total_90d
  FROM public.crawler_visits WHERE ts >= v_since_90d;

  -- ── 3) bots_breakdown: { bot_name: { count, owner } } — from mv_crawler_bots_30d,
  --      same "predominant owner per bot_name" reduction as get_crawler_summary() ──
  SELECT jsonb_object_agg(bot_name, jsonb_build_object('count', total_cnt, 'owner', top_owner))
    INTO v_bots
  FROM (
    SELECT
      bot_name,
      SUM(visit_count) AS total_cnt,
      (array_agg(bot_owner ORDER BY visit_count DESC NULLS LAST))[1] AS top_owner
    FROM public.mv_crawler_bots_30d
    GROUP BY bot_name
    ORDER BY total_cnt DESC
    LIMIT 50
  ) b;

  -- ── 4) sites_breakdown: { site: count } — no MV covers this (mv_crawler_
  --      industries_30d only has industries). Consumed by
  --      crawler_stats_precompute.py (site_ratios) — confirmed via grep, so
  --      it cannot be left null. Lightweight independent GROUP BY using
  --      idx_crawler_visits_site_ts (~2s benchmarked), not the slow CTE. ──
  SELECT jsonb_object_agg(site_key, cnt) INTO v_sites
  FROM (
    SELECT COALESCE(LOWER(site), 'cloudpipe-macao-app') AS site_key, COUNT(*) AS cnt
    FROM public.crawler_visits
    WHERE ts >= v_since_30d
    GROUP BY 1
    ORDER BY cnt DESC
  ) s;

  -- ── 5) industries_breakdown: { industry: count } — from mv_crawler_industries_30d
  --      (already excludes 'insights' pseudo-industry + spider-web/page/robots/
  --      api-faq/faqs page_types per 20260530_exclude_insights_from_industries.sql) ──
  SELECT jsonb_object_agg(industry, visit_count) INTO v_industries
  FROM (
    SELECT industry, visit_count
    FROM public.mv_crawler_industries_30d
    ORDER BY visit_count DESC
    LIMIT 50
  ) i;

  -- ── 6) daily_30d: { "YYYY-MM-DD": count } — from mv_crawler_daily_30d,
  --      summed across bot_owner (HKT day bucketing already baked into the MV) ──
  SELECT jsonb_object_agg(day::text, day_total ORDER BY day) INTO v_daily
  FROM (
    SELECT day, SUM(visit_count) AS day_total
    FROM public.mv_crawler_daily_30d
    GROUP BY day
  ) d;

  -- ── 7) daily_by_owner_30d: { "YYYY-MM-DD": { owner: count } } — mv_crawler_daily_30d
  --      already has (day, bot_owner, visit_count), so this is a direct nested agg ──
  SELECT jsonb_object_agg(day::text, owners ORDER BY day) INTO v_daily_by_owner
  FROM (
    SELECT day, jsonb_object_agg(bot_owner, visit_count) AS owners
    FROM public.mv_crawler_daily_30d
    GROUP BY day
  ) o;

  INSERT INTO public.crawler_stats_cache (
    id, total_visits_1d, total_visits_7d, total_visits_30d, total_visits_90d,
    unique_bots, bots_breakdown, sites_breakdown, industries_breakdown,
    daily_30d, daily_by_owner_30d, generated_at, last_refresh_error
  ) VALUES (
    1, v_total_1d, v_total_7d, v_total_30d, v_total_90d,
    v_unique_bots, v_bots, v_sites, v_industries,
    v_daily, v_daily_by_owner, NOW(), NULL
  )
  ON CONFLICT (id) DO UPDATE SET
    total_visits_1d      = EXCLUDED.total_visits_1d,
    total_visits_7d      = EXCLUDED.total_visits_7d,
    total_visits_30d     = EXCLUDED.total_visits_30d,
    total_visits_90d     = EXCLUDED.total_visits_90d,
    unique_bots          = EXCLUDED.unique_bots,
    bots_breakdown        = EXCLUDED.bots_breakdown,
    sites_breakdown       = EXCLUDED.sites_breakdown,
    industries_breakdown  = EXCLUDED.industries_breakdown,
    daily_30d             = EXCLUDED.daily_30d,
    daily_by_owner_30d    = EXCLUDED.daily_by_owner_30d,
    generated_at          = EXCLUDED.generated_at,
    last_refresh_error    = NULL;

EXCEPTION WHEN OTHERS THEN
  -- Fail-loud, visible from the table itself (not just pg_cron/warning logs).
  -- Kept as a genuine safety net now that the happy path is fast — this
  -- should rarely fire, so if it does, it is worth someone's attention.
  RAISE WARNING 'refresh_crawler_stats_cache failed: %', SQLERRM;
  UPDATE public.crawler_stats_cache
    SET last_refresh_error = SQLERRM || ' @ ' || NOW()::text
    WHERE id = 1;
END;
$function$;

-- ---------------------------------------------------------------------------
-- B. Chain refresh_crawler_stats_cache() onto the existing v2 cron job so
--    crawler_stats_cache table auto-refreshes every 30 min again, using MV
--    data that was just refreshed by the preceding statement in the same
--    job run (same-transaction read-your-own-writes; jobid=1 already proven
--    to run multi-statement commands successfully — see cron.job_run_details
--    history, 10-30s per run, well inside the existing 60s SET LOCAL budget).
-- ---------------------------------------------------------------------------
SELECT cron.alter_job(
  1,
  command => $cron$SET LOCAL statement_timeout = '60s'; SELECT refresh_crawler_stats_cache_v2(); SELECT refresh_crawler_stats_cache();$cron$
);

COMMIT;

-- Run once immediately to seed/verify (outside the transaction so a failure
-- here doesn't roll back the function/cron changes above — matches the
-- original migration's own pattern of "run once immediately to seed").
SELECT refresh_crawler_stats_cache();
