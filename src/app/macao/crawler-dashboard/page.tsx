// Password check + session cookie now live server-side in
// /api/macao/crawler-dashboard-auth — the plaintext password no longer ships
// in the client JS bundle (previously `DASHBOARD_PASSWORD` was readable via view-source).
function PasswordGate({ children }: { children: React.ReactNode }) {
  const [authed, setAuthed] = useState<boolean | null>(null) // null = checking with server
  const [input, setInput] = useState('')
  const [error, setError] = useState(false)
  const [checking, setChecking] = useState(false)

  useEffect(() => {
    let cancelled = false
    fetch('/api/macao/crawler-dashboard-auth')
      .then(r => r.json())
      .then(d => { if (!cancelled) setAuthed(!!d.authed) })
      .catch(() => { if (!cancelled) setAuthed(false) })
    return () => { cancelled = true }
  }, [])

  const submit = async () => {
    if (checking) return
    setChecking(true)
    setError(false)
    try {
      const res = await fetch('/api/macao/crawler-dashboard-auth', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ password: input }),
      })
      const data = await res.json()
      if (data.ok) setAuthed(true)
      else setError(true)
    } catch {
      setError(true)
    } finally {
      setChecking(false)
    }
  }

  if (authed === null) {
    return (
      <div style={{ display: 'flex', justifyContent: 'center', alignItems: 'center', minHeight: '100vh', background: '#f5f5f5' }}>
        <p style={{ color: '#999', fontSize: 13 }}>驗證中...</p>
      </div>
    )
  }

  if (authed) return <>{children}</>

  return (
    <div style={{ display: 'flex', justifyContent: 'center', alignItems: 'center', minHeight: '100vh', background: '#f5f5f5' }}>
      <div style={{ background: 'white', padding: 40, borderRadius: 12, boxShadow: '0 2px 20px rgba(0,0,0,0.1)', textAlign: 'center', maxWidth: 360 }}>
        <h2 style={{ marginBottom: 8, color: '#0f4c81' }}>🔒 Dashboard Access</h2>
        <p style={{ color: '#888', fontSize: 14, marginBottom: 20 }}>Internal use only</p>
        <input
          type="password"
          value={input}
          onChange={e => { setInput(e.target.value); setError(false) }}
          onKeyDown={e => { if (e.key === 'Enter') submit() }}
          placeholder="Password"
          style={{ width: '100%', padding: '10px 14px', border: `1px solid ${error ? '#dc2626' : '#ddd'}`, borderRadius: 8, fontSize: 16, marginBottom: 12 }}
        />
        <button
          onClick={submit}
          disabled={checking}
          style={{ width: '100%', padding: '10px', background: '#0f4c81', color: 'white', border: 'none', borderRadius: 8, fontSize: 14, cursor: checking ? 'wait' : 'pointer', opacity: checking ? 0.7 : 1 }}
        >{checking ? '驗證中...' : 'Enter'}</button>
        {error && <p style={{ color: '#dc2626', fontSize: 13, marginTop: 8 }}>Incorrect password</p>}
      </div>
    </div>
  )
}

// ── GSAP number counter hook ──────────────────────────────────────────────────
function useCountUp(target: number, duration = 1.2, decimals = 0): string {
  const [display, setDisplay] = useState('0')
  const tweenRef = useRef<gsap.core.Tween | null>(null)
  const objRef = useRef({ value: 0 })
  useEffect(() => {
    if (typeof window === 'undefined') return
    tweenRef.current?.kill()
    const fmt = (n: number) => decimals > 0 ? n.toFixed(decimals) : Math.round(n).toLocaleString()
    if (target === 0) { setDisplay('0'); return }
    tweenRef.current = gsap.to(objRef.current, {
      value: target,
      duration,
      ease: 'power3.out',
      onUpdate: () => setDisplay(fmt(objRef.current.value)),
      onComplete: () => setDisplay(fmt(target)),
    })
    return () => { tweenRef.current?.kill() }
  }, [target, duration, decimals])
  return display
}

// ── Animated bar component (GSAP) ────────────────────────────────────────────
function AnimBar({ pct, color, height = 6 }: { pct: number; color: string; height?: number }) {
  const ref = useRef<HTMLDivElement>(null)
  useEffect(() => {
    if (!ref.current) return
    gsap.fromTo(ref.current,
      { width: '0%' },
      { width: `${Math.min(pct, 100)}%`, duration: 0.9, ease: 'power3.out' }
    )
  }, [pct])
  return (
    <div style={{ background: '#e5e5e5', borderRadius: 4, height, overflow: 'hidden' }}>
      <div ref={ref} style={{ height: '100%', borderRadius: 4, background: color, width: '0%' }} />
    </div>
  )
}

// ── Daily trend chart (HKT date labels — precompute script uses HKT day boundaries) ──
// `days` is the selected window; `granularity` folds the series into weeks/months when the
// window is long ("全部" view). The old cap (30 bars) made a 90-day selection look like 30 days.
function DailyTrendChart({ daily, days, granularity = 'day', basisNote }: {
  daily: { date: string; total: number }[]; days: number; granularity?: Granularity; basisNote?: string
}) {
  const barsRef = useRef<(HTMLDivElement | null)[]>([])
  // Precompute script labels days with HKT date (UTC+8); must match here or today bar turns wrong
  const hktToday = new Date(Date.now() + 8 * 3600000).toISOString().slice(0, 10)
  const series: AggPoint[] = aggregateSeries(daily, granularity)
  const sliced = granularity === 'day' && days !== ALL_DAYS ? series.slice(-barLimit(days)) : series
  const maxVal = Math.max(...sliced.map(d => d.total), 1)
  const datesKey = sliced.map(d => d.date).join(',')
  const unit = granularity === 'week' ? '每週' : granularity === 'month' ? '每月' : '每日'

  useEffect(() => {
    barsRef.current.forEach((el, i) => {
      if (!el) return
      const pct = (sliced[i]?.total / maxVal) * 100
      gsap.fromTo(el,
        { height: '0%', opacity: 0 },
        { height: `${pct}%`, opacity: 1, duration: 0.7, delay: Math.min(i * 0.03, 1), ease: 'power2.out' }
      )
    })
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [datesKey])

  if (!sliced.length) return null

  const last = sliced[sliced.length - 1]
  return (
    <div style={{ background: '#fafafa', borderRadius: 10, padding: '16px 16px 10px', border: '1px solid #eee', gridColumn: '1 / -1' }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'baseline', marginBottom: 12 }}>
        <h3 style={{ fontSize: 14, fontWeight: 600, margin: 0, color: '#333' }}>{unit}爬蟲訪問趨勢</h3>
        <span style={{ fontSize: 11, color: '#aaa' }}>{basisNote || '日期按 HKT'}{granularity !== 'day' ? '｜首尾週期可能不完整' : ''}</span>
      </div>
      <div style={{ display: 'flex', alignItems: 'flex-end', gap: 3, height: 80, overflowX: 'auto' }} data-testid="trend-bars" data-bars={sliced.length}>
        {sliced.map((d, i) => {
          const isToday = granularity === 'day' && d.date === hktToday
          const barColor = isToday ? '#10a37f' : d.partial ? '#9db8e8' : '#4285f4'
          return (
            <div key={d.date} title={`${d.title}${granularity === 'day' ? ' (HKT)' : ''}: ${d.total.toLocaleString()} visits`}
              style={{ flex: '1 0 auto', minWidth: granularity === 'day' ? 18 : 26, display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 3, height: '100%', cursor: 'default' }}>
              <div style={{ flex: 1, width: '100%', display: 'flex', alignItems: 'flex-end', position: 'relative' }}>
                <div
                  ref={el => { barsRef.current[i] = el }}
                  style={{ width: '100%', background: barColor, borderRadius: '3px 3px 0 0', height: '0%', opacity: 0 }}
                />
              </div>
              <span style={{ fontSize: 9, color: isToday ? '#10a37f' : '#aaa', fontWeight: isToday ? 700 : 400, whiteSpace: 'nowrap' }}>
                {d.label}
              </span>
            </div>
          )
        })}
      </div>
      <div style={{ display: 'flex', justifyContent: 'space-between', marginTop: 6, fontSize: 11, color: '#bbb' }}>
        <span>峰值: {Math.max(...sliced.map(d => d.total)).toLocaleString()}</span>
        {granularity === 'day'
          ? <span>今日: {(sliced.find(d => d.date === hktToday)?.total ?? last.total).toLocaleString()}</span>
          : <span>最近一期: {last.total.toLocaleString()}</span>}
        <span>合計: {sliced.reduce((s, d) => s + d.total, 0).toLocaleString()}</span>
      </div>
    </div>
  )
}

// ── Fade-in card wrapper (GSAP) ──────────────────────────────────────────────
function FadeCard({ children, delay = 0, style, className }: { children: React.ReactNode; delay?: number; style?: React.CSSProperties; className?: string }) {
  const ref = useRef<HTMLDivElement>(null)
  useEffect(() => {
    if (!ref.current) return
    gsap.from(ref.current, {
      y: 20, opacity: 0, duration: 0.6,
      delay: delay / 1000,
      ease: 'power3.out',
      clearProps: 'all',
    })
  }, [delay])
  return <div ref={ref} style={style} className={className}>{children}</div>
}

